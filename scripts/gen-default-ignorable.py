#!/usr/bin/env python3
"""Generate baud-font/src/ignorable.rs from the pinned DerivedCoreProperties.

`Default_Ignorable_Code_Point` (`[[source: dcp-data]]`)
is the set a shaper skips while matching unless a pattern names the glyph
itself -- ZWJ, ZWNJ, variation selectors, tags and the like. HarfBuzz's
`may_skip` answers "maybe" for these, and baud-font's matcher does the same.

The ranges are emitted as a sorted `&[(u32, u32)]` const, inclusive, so the
lookup is a binary search over a table the generator wrote rather than a
list somebody typed. Positive controls: U+200D (ZWJ) and U+FE0F (VS16) must
be in, U+0041 and U+1F600 must be out.

Usage: gen-default-ignorable.py <DerivedCoreProperties.txt> <out.rs>
"""

import sys


def main():
    src, dst = sys.argv[1], sys.argv[2]
    ranges = []
    for line in open(src, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line or "Default_Ignorable_Code_Point" not in line:
            continue
        cps, prop = [f.strip() for f in line.split(";")[:2]]
        if prop != "Default_Ignorable_Code_Point":
            continue
        if ".." in cps:
            a, b = cps.split("..")
        else:
            a = b = cps
        ranges.append((int(a, 16), int(b, 16)))
    ranges.sort()
    merged = []
    for a, b in ranges:
        if merged and merged[-1][1] + 1 >= a:
            merged[-1] = (merged[-1][0], max(merged[-1][1], b))
        else:
            merged.append((a, b))

    def has(cp):
        return any(a <= cp <= b for a, b in merged)

    assert has(0x200D) and has(0xFE0F) and has(0xE0067) and not has(0x41) and not has(0x1F600)
    out = [
        "//! `Default_Ignorable_Code_Point`, generated by",
        "//! `scripts/gen-default-ignorable.py` from",
        "//! `[[source: dcp-data]]`. Do not edit; regenerate.",
        "",
        "/// Sorted, inclusive, non-overlapping ranges.",
        "pub const DEFAULT_IGNORABLE: &[(u32, u32)] = &[",
    ]
    for a, b in merged:
        out.append(f"    (0x{a:04X}, 0x{b:04X}),")
    out.append("];")
    out.append("")
    open(dst, "w").write("\n".join(out))
    print(f"{dst}: {len(merged)} ranges from {len(ranges)} lines")


if __name__ == "__main__":
    main()
