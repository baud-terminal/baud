"""HarfBuzz's and FreeType's drawings of the vertical cases, as baud-font's
oracle for components placed on vertical phantom points.

Writes baud-font/tests/var/vertical.txt: every glyph of
tests/var/vertical-cases.ttf (scripts/vertical-cases-font.py) at the
default instance and at wght 100, 650 and 900, drawn by HarfBuzz (its draw
functions, font units) and by FreeType (FT_LOAD_NO_SCALE |
FT_LOAD_NO_HINTING, the outline's points as loaded), one row per engine.
Every contour of the font is a polygon that starts on the curve, so a row
is each contour's points in order, and the two engines' rows and baud's
compare point for point. A glyph FreeType refuses to load is written
`ERROR` with FreeType's message. The two engines disagree on some glyphs
on purpose; tests/vertical.rs says which the specification sides with.

    nix shell --impure --expr 'with import (builtins.getFlake "nixpkgs") {}; \
      python3.withPackages (p: [ p.uharfbuzz p.freetype-py ])' \
      -c python3 scripts/vertical-oracle.py
"""
import os
import freetype
import uharfbuzz as hb

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FONT = os.path.join(ROOT, "baud-font/tests/var/vertical-cases.ttf")
OUT = os.path.join(ROOT, "baud-font/tests/var/vertical.txt")
SETTINGS = [None, 100, 650, 900]


def contours_hb(font, gid):
    out = []
    funcs = hb.DrawFuncs()
    funcs.set_move_to_func(lambda x, y, c: c.append([(x, y)]))
    funcs.set_line_to_func(lambda x, y, c: c[-1].append((x, y)))
    funcs.set_quadratic_to_func(lambda *a: a[-1][-1].append("Q"))
    funcs.set_cubic_to_func(lambda *a: a[-1][-1].append("C"))
    funcs.set_close_path_func(lambda c: None)
    font.draw_glyph(gid, funcs, out)
    return [c[:-1] if len(c) > 1 and c[-1] == c[0] else c for c in out]


def contours_ft(face, gid):
    face.load_glyph(gid, freetype.FT_LOAD_NO_SCALE | freetype.FT_LOAD_NO_HINTING)
    o = face.glyph.outline
    out, start = [], 0
    for end in o.contours:
        pts = o.points[start:end + 1]
        tags = o.tags[start:end + 1]
        if any(not (t & 1) for t in tags):
            out.append(["Q"])
        else:
            out.append([(float(x), float(y)) for x, y in pts])
        start = end + 1
    return out


def fmt(contours):
    if not contours:
        return "-"
    return "|".join(
        ";".join(p if isinstance(p, str) else f"{p[0]:.4f},{p[1]:.4f}" for p in c)
        for c in contours
    )


blob = hb.Blob.from_file_path(FONT)
hface = hb.Face(blob)
names = [hb.Font(hface).get_glyph_name(g) for g in range(hface.glyph_count)]
lines = [
    f"# glyph  name  wght (or - for the default)  engine  contours"
    f"  (HarfBuzz {hb.version_string()}, uharfbuzz {hb.__version__},"
    f" FreeType {'.'.join(map(str, freetype.version()))})",
    "# generated by scripts/vertical-oracle.py; do not edit",
]
for w in SETTINGS:
    font = hb.Font(hface)
    font.scale = (hface.upem, hface.upem)
    ft = freetype.Face(FONT)
    if w is not None:
        font.set_variations({"wght": w})
        ft.set_var_design_coords([w])
    label = "-" if w is None else str(w)
    for gid in range(1, hface.glyph_count):
        lines.append(f"{gid} {names[gid]} {label} hb {fmt(contours_hb(font, gid))}")
        try:
            row = fmt(contours_ft(ft, gid))
        except freetype.FT_Exception as e:
            row = "ERROR " + str(e).replace(" ", "_")
        lines.append(f"{gid} {names[gid]} {label} ft {row}")
# The same font with its `vhea` and `vmtx` tags renamed in the table
# directory: a face with no vertical metrics, which HarfBuzz reads as a tsb
# of 0 and an advance height of unitsPerEm. Drawn at the default instance,
# engine `hb-novmtx`. (Renaming `vhea` alone leaves a `vmtx` with no long
# records: HarfBuzz reads every tsb as 0 and, since this table holds more
# two-byte entries than the face has glyphs, takes the surplus's count as
# its number of advance heights and reads that many u16s from the table's
# start, glyph g reading entry min(g, count - 1).)
data = bytearray(open(FONT, "rb").read())
n = int.from_bytes(data[4:6], "big")
for tag, to in ((b"vhea", b"xhea"), (b"vmtx", b"xmtx")):
    renamed = [i for i in range(n) if data[12 + 16 * i:16 + 16 * i] == tag]
    assert len(renamed) == 1
    data[12 + 16 * renamed[0]:16 + 16 * renamed[0]] = to
nface = hb.Face(hb.Blob(bytes(data)))
nfont = hb.Font(nface)
nfont.scale = (nface.upem, nface.upem)
for gid in range(1, nface.glyph_count):
    lines.append(f"{gid} {names[gid]} - hb-novmtx {fmt(contours_hb(nfont, gid))}")
with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")
print(len(lines) - 2, "rows")
