"""HarfBuzz's advances at a variation, as baud-font's HVAR oracle.

Writes baud-font/tests/var/advances.txt: for each committed variable test
font, the horizontal advance HarfBuzz gives each glyph -- every glyph of
the cases fonts, every 11th of the real ones -- at the default instance and
at the settings named below, and one glyph id past the face at each
setting, in font units (the font's scale is its units
per em). The default rows are the control: they must be the hmtx advance,
which says the scale is units per em before a varied row is compared.

    nix shell --impure --expr 'with import (builtins.getFlake "nixpkgs") {}; \
      python3.withPackages (p: [ p.uharfbuzz ])' -c python3 scripts/advance-oracle.py
"""
import os
import uharfbuzz as hb

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
TESTS = os.path.join(ROOT, "baud-font/tests")
# wght 650 is 0.5 exactly, which puts a unit delta on a half.
CASES = [{}] + [
    {"wght": w, "wdth": d} if d != 100 else {"wght": w}
    for w in (100, 150, 400, 525, 650, 775, 900)
    for d in (50, 75, 100, 150, 200)
    if (w, d) != (400, 100)
]
REAL = [{}] + [{"wght": w} for w in (100, 350, 650, 700, 800)]
FIRA = [{}] + [{"wght": w} for w in (300, 450, 550, 700)]
FONTS = [
    ("fonts/JetBrainsMono-Variable.ttf", REAL, 11),
    ("fonts/JetBrainsMono-Italic-Variable.ttf", REAL, 11),
    ("fonts/FiraCode-VF.ttf", FIRA, 11),
    ("var/gvar-cases.ttf", CASES, 1),
] + [
    (f"var/hvar/{n}", CASES, 1)
    for n in sorted(os.listdir(os.path.join(TESTS, "var/hvar")))
    if n.endswith(".ttf")
]

rows = 0
with open(os.path.join(TESTS, "var/advances.txt"), "w") as out:
    out.write(f"# font  axis=value,... (or - for the default)  glyph  advance"
              f"  (HarfBuzz {hb.version_string()}, uharfbuzz {hb.__version__})\n")
    out.write("# generated by scripts/advance-oracle.py; do not edit\n")
    for name, settings, step in FONTS:
        blob = hb.Blob.from_file_path(os.path.join(TESTS, name))
        face = hb.Face(blob)
        for s in settings:
            font = hb.Font(face)
            if s:
                font.set_variations(s)
            label = ",".join(f"{k}={v}" for k, v in s.items()) or "-"
            for gid in range(0, face.glyph_count, step):
                out.write(f"{name} {label} {gid} {font.get_glyph_h_advance(gid)}\n")
                rows += 1
            # One glyph id past the face, where a coordinate is not the
            # default: HarfBuzz's hmtx answers 0 there, to which HVAR still
            # adds its delta (the map clamps). At the default instance baud
            # answers ttf-parser's nothing, which tests/oracle.rs holds.
            if any(font.get_var_coords_normalized()):
                gid = face.glyph_count
                out.write(f"{name} {label} {gid} {font.get_glyph_h_advance(gid)}\n")
                rows += 1
print(rows, "rows")
