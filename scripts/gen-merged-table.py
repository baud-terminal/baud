#!/usr/bin/env python3
"""Format the merged Unicode property table dumped by baud-domain's test.

    cargo test --release -p baud-domain --test merged_size -- --ignored
    python3 scripts/gen-merged-table.py

Byte strings, not array literals: rustfmt rewraps `[0, 1, 2, ...]`, so the file
the generator writes would not be the file that gets committed and `--check`
would fail. The width and grapheme generators carry the same warning.
"""
import struct, sys, pathlib

raw = pathlib.Path("baud-domain/merged.bin").read_bytes()
ni, nb, npal = struct.unpack_from("<III", raw, 0)
o = 12
index, blocks = raw[o:o+ni], raw[o+ni:o+ni+nb]
pal = raw[o+ni+nb:o+ni+nb+npal*3]
bmp = raw[o+ni+nb+npal*3:]
assert len(bmp) == 0x10000 * 2, f"flat BMP is {len(bmp)} bytes"

def bytestr(v, per=24):
    out = []
    for i in range(0, len(v), per):
        out.append("".join(f"\\x{b:02x}" for b in v[i:i+per]))
    return "\\\n    ".join(out)

total = ni + nb + npal * 3
src = f'''//! Generated by `baud-domain/tests/merged_size.rs::emit_merged_table` and
//! `scripts/gen-merged-table.py`. Do not edit.
//!
//! **One table for both questions the per-character path asks.** `Width::of`
//! and `GraphemeClass::of_with_lookback` were two two-stage tries over the
//! same `cp >> 8` shape: four loads and 44,032 bytes to answer what is really
//! one question about one codepoint.
//!
//! Packing the fields does not work -- the grapheme leaf already spends all
//! eight bits on four of class and four of lookback, and width needs two more,
//! so a merged leaf would be two bytes and the table would grow to 67,328.
//!
//! Only **{npal}** distinct `(class, lookback, width)` triples occur in the whole
//! of Unicode, out of a possible 672. So the leaf indexes a palette instead of
//! packing: one byte, {total} bytes of table, and two loads.
//!
//! `the_merged_table_agrees_with_both_tries` checks every one of the 1,114,112
//! codepoints against the two tries this replaces.

/// `(class, lookback, width)` per palette id.
pub static MERGED_PALETTE: &[u8; {npal * 3}] = b"\\
    {bytestr(pal)}";

/// `cp >> 8` to a block of [`MERGED_BLOCKS`].
pub static MERGED_INDEX: &[u8; {ni}] = b"\\
    {bytestr(index)}";

/// {nb // 256} deduplicated blocks of 256 palette ids.
pub static MERGED_BLOCKS: &[u8; {nb}] = b"\\
    {bytestr(blocks)}";

/// The Basic Multilingual Plane, **flat**: one load, no stage-1 indirection.
///
/// Little-endian `u16` per codepoint, `class | lookback << 4 | width << 8`.
/// 128 KB of rodata, and only the touched pages cost anything -- `cat-cjk.raw`
/// uses 3,175 distinct BMP codepoints, which is **113 cache lines, 7.1 KB**.
///
/// Depth is the point. Every other table here is two dependent loads; this is
/// one, and on this path a change is only worth making if it shortens the
/// critical path.
pub static BMP_DIRECT: &[u8; {len(bmp)}] = b"\\
    {bytestr(bmp)}";
'''
pathlib.Path("baud-domain/src/merged_data.rs").write_text(src)
print(f"  merged_data.rs: index {ni}, blocks {nb//256}, palette {npal} -> {total} bytes")
print(f"  flat BMP: {len(bmp)} bytes of rodata, 113 lines touched by cat-cjk")
print(f"  against the two tries' 44,032 = {100*(total/44032-1):+.0f}%")
