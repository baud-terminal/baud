"""HarfBuzz's normalised variation coordinates, as baud-font's oracle.

Writes baud-font/tests/var/normalize.txt: for each committed variable test
font, every wght design value from 0 to 1000 in quarter units (the axis
ranges are inside that, so both clamps are exercised), with the 2.14
coordinate HarfBuzz computes. The OpenType specification fixes the
arithmetic -- 16.16 in, clamp, avar, then add 2 and shift right by 2 --
except the rounding of the 16.16 division, which HarfBuzz decides here.

    nix shell --impure --expr 'with import (builtins.getFlake "nixpkgs") {}; \
      python3.withPackages (p: [ p.uharfbuzz ])' -c python3 scripts/var-oracle.py
"""
import os
import uharfbuzz as hb

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FONTS = ["FiraCode-VF.ttf", "JetBrainsMono-Italic-Variable.ttf", "JetBrainsMono-Variable.ttf"]

lines = [
    "# font  wght-design-in-quarters  normalised-2.14-as-integer  (HarfBuzz "
    + hb.version_string() + ", uharfbuzz " + hb.__version__ + ")",
    "# generated by scripts/var-oracle.py; do not edit",
]
for name in FONTS:
    blob = hb.Blob.from_file_path(os.path.join(ROOT, "baud-font/tests/fonts", name))
    font = hb.Font(hb.Face(blob))
    for q in range(0, 4001):
        font.set_variations({"wght": q / 4})
        (coord,) = font.get_var_coords_normalized()
        f214 = coord * 16384
        assert f214 == int(f214), (name, q, coord)
        lines.append(f"{name} {q} {int(f214)}")
with open(os.path.join(ROOT, "baud-font/tests/var/normalize.txt"), "w") as f:
    f.write("\n".join(lines) + "\n")
print(len(lines) - 2, "coordinates")
