"""HarfBuzz's and FreeType's drawings of the bearing cases, as baud-font's
left-side-bearing oracle.

Writes baud-font/tests/var/bearings.txt: every glyph of
tests/var/bearing-cases.ttf and bearing-cases-bit1.ttf
(scripts/bearing-cases-font.py) at the default instance and at wght 100,
650 and 900, drawn by HarfBuzz (its draw functions, font units) and by
FreeType (FT_LOAD_NO_SCALE | FT_LOAD_NO_HINTING, the outline's points as
loaded), one row per engine, in scripts/component-oracle.py's format with
the font's file name first. A glyph FreeType refuses is written `ERROR`
with its message. Each glyph's `start` row is where its left phantom
starts at the default instance, `xMin - lsb` -- a USE_MY_METRICS
component's, the last one's, where a composite has one -- read by
fontTools, so baud's test does not take it from the code it checks.

    nix shell --impure --expr 'with import (builtins.getFlake "nixpkgs") {}; \
      python3.withPackages (p: [ p.uharfbuzz p.freetype-py p.fonttools ])' \
      -c python3 scripts/bearing-oracle.py
"""
import os
import freetype
import uharfbuzz as hb
from fontTools.ttLib import TTFont

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DIR = os.path.join(ROOT, "baud-font/tests/var")
FONTS = ["bearing-cases.ttf", "bearing-cases-bit1.ttf"]
OUT = os.path.join(DIR, "bearings.txt")
SETTINGS = [None, 100, 650, 900]
USE_MY_METRICS = 0x0200


def contours_hb(font, gid):
    out = []
    funcs = hb.DrawFuncs()
    funcs.set_move_to_func(lambda x, y, c: c.append([(x, y)]))
    funcs.set_line_to_func(lambda x, y, c: c[-1].append((x, y)))
    funcs.set_quadratic_to_func(lambda *a: a[-1][-1].append("Q"))
    funcs.set_cubic_to_func(lambda *a: a[-1][-1].append("C"))
    funcs.set_close_path_func(lambda c: None)
    font.draw_glyph(gid, funcs, out)
    return [c[:-1] if len(c) > 1 and c[-1] == c[0] else c for c in out]


def contours_ft(face, gid):
    face.load_glyph(gid, freetype.FT_LOAD_NO_SCALE | freetype.FT_LOAD_NO_HINTING)
    o = face.glyph.outline
    out, start = [], 0
    for end in o.contours:
        pts = o.points[start:end + 1]
        tags = o.tags[start:end + 1]
        if any(not (t & 1) for t in tags):
            out.append(["Q"])
        else:
            out.append([(float(x), float(y)) for x, y in pts])
        start = end + 1
    return out


def fmt(contours):
    if not contours:
        return "-"
    return "|".join(
        ";".join(p if isinstance(p, str) else f"{p[0]:.4f},{p[1]:.4f}" for p in c)
        for c in contours
    )


def starts(path):
    f = TTFont(path)
    glyf, hmtx = f["glyf"], f["hmtx"].metrics

    def start(name):
        g = glyf[name]
        at = getattr(g, "xMin", 0) - hmtx[name][1]
        if g.isComposite():
            for c in g.components:
                if c.flags & USE_MY_METRICS:
                    at = start(c.glyphName)
        return at

    return {n: start(n) for n in f.getGlyphOrder()}


lines = [
    f"# font  glyph  name  wght (or - for the default)  engine  contours"
    f"  (HarfBuzz {hb.version_string()}, uharfbuzz {hb.__version__},"
    f" FreeType {'.'.join(map(str, freetype.version()))})",
    "# font  glyph  name  start  pp1 at the default instance (fontTools)",
    "# generated by scripts/bearing-oracle.py; do not edit",
]
for file in FONTS:
    path = os.path.join(DIR, file)
    blob = hb.Blob.from_file_path(path)
    hface = hb.Face(blob)
    names = [hb.Font(hface).get_glyph_name(g) for g in range(hface.glyph_count)]
    s = starts(path)
    for gid in range(1, hface.glyph_count):
        lines.append(f"{file} {gid} {names[gid]} start {s[names[gid]]}")
    for w in SETTINGS:
        font = hb.Font(hface)
        font.scale = (hface.upem, hface.upem)
        ft = freetype.Face(path)
        if w is not None:
            font.set_variations({"wght": w})
            ft.set_var_design_coords([w])
        label = "-" if w is None else str(w)
        for gid in range(1, hface.glyph_count):
            lines.append(f"{file} {gid} {names[gid]} {label} hb {fmt(contours_hb(font, gid))}")
            try:
                row = fmt(contours_ft(ft, gid))
            except freetype.FT_Exception as e:
                row = "ERROR " + str(e).replace(" ", "_")
            lines.append(f"{file} {gid} {names[gid]} {label} ft {row}")
with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")
print(len(lines) - 3, "rows")
