#!/usr/bin/env python3
"""Write a synthetic payload of scrolling text in which many cells carry
combining marks, for the `frame` bench's marked-cell rows.

    python3 scripts/gen-marks-payload.py marks   target/marks.raw
    python3 scripts/gen-marks-payload.py covered target/marks-covered.raw
    cargo bench -p baud-bench --bench frame -- ../../target/marks.raw 5

(`frame` reads its recording relative to `tests/recordings/`, and `target/`
keeps the generated bytes out of the tree.)

**It is synthetic, and a number from it is a claim about marked cells, not
about a session.** No recording in `tests/recordings/` carries marks densely
enough to price the per-cluster face choice: cat-cjk and vim-unicode have a
few dozen marked cells. So this prices the marked path and nothing else, the
way `payload::cjk` prices wide text.

The seed is fixed, so every run writes the same bytes: about 1 MiB, lines of
120 to 199 columns, 15% spaces. Per letter (from `aeiouqwxnrst`):

* `marks`: 60% bare; 12% + U+0301 (acute: composes on a vowel, a mark glyph
  on q, w and x); 10% + U+0323 (dot below); 6% + U+0301 + U+0323; 4% +
  U+0305 (JetBrains Mono lacks it, Fira Code has it); 3% q + U+0316 + U+0301
  (no test face has U+0316); 2% + U+0305 + U+0309 (JetBrains Mono lacks
  U+0305, Fira Code lacks U+0309); 3% + U+0301 + U+200D (an ignorable rides
  along).
* `covered`: the same draws, with only the marks JetBrains Mono has: 60%
  bare, 12% + U+0301, 10% + U+0323, 18% + U+0301 + U+0323. So no cluster
  is moved or dropped, and the row prices the coverage test alone.

Both share one random sequence (a draw per letter decides its marks whatever
the mix), so `covered` is `marks` with the uncovered marks replaced.
"""
import random
import sys

LETTERS = "aeiouqwxnrst"

# (upper bound of the draw, what follows the letter); `None` is q + U+0316 +
# U+0301 in place of the letter drawn.
MIXES = {
    "marks": [
        (0.60, ""),
        (0.72, "́"),
        (0.82, "̣"),
        (0.88, "̣́"),
        (0.92, "̅"),
        (0.95, None),
        (0.97, "̅̉"),
        (1.00, "́‍"),
    ],
    "covered": [
        (0.60, ""),
        (0.72, "́"),
        (0.82, "̣"),
        (1.00, "̣́"),
    ],
}


def cell(mix, rng):
    base = rng.choice(LETTERS)
    r = rng.random()
    for bound, marks in mix:
        if r < bound:
            return "q̖́" if marks is None else base + marks
    return base


def main():
    if len(sys.argv) not in (3, 4) or sys.argv[1] not in MIXES:
        sys.exit(f"usage: {sys.argv[0]} {{{'|'.join(MIXES)}}} OUT [BYTES]")
    mix = MIXES[sys.argv[1]]
    target = int(sys.argv[3]) if len(sys.argv) == 4 else 1 << 20
    rng = random.Random(20261007)
    out, total = [], 0
    while total < target:
        cols = rng.randint(120, 199)
        line = []
        for _ in range(cols):
            if rng.random() < 0.15:
                line.append(" ")
            else:
                line.append(cell(mix, rng))
        data = ("".join(line) + "\r\n").encode()
        out.append(data)
        total += len(data)
    with open(sys.argv[2], "wb") as f:
        f.write(b"".join(out))
    print(total, "bytes,", len(out), "lines")


if __name__ == "__main__":
    main()
