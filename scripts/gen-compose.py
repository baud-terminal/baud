#!/usr/bin/env python3
"""Generate baud-font/src/compose.rs: canonical composition and decomposition.

From UnicodeData.txt (`[[source: unicode-data]]`) field 5, the untagged
(canonical) decompositions, and DerivedNormalizationProps.txt
(`[[source: unicode-dnp]]`), Full_Composition_Exclusion:

* `COMPOSE`: sorted `(first, second, composed)` for every canonical pair
  decomposition whose composite is not excluded -- the primary composites.
  Hangul syllables are not listed; they compose by arithmetic.
* `DECOMPOSE`: sorted `(codepoint, first, second)` for every canonical
  decomposition, singletons with `second = 0`. Not recursive: a consumer that
  needs the full decomposition applies it again to `first`.

Positive controls: e + U+0301 -> U+00E9 and A + U+030A -> U+00C5 compose;
U+0915 + U+093C does NOT compose to U+0958 (excluded); U+212B ANGSTROM SIGN
decomposes to U+00C5 as a singleton.

Usage: gen-compose.py <UnicodeData.txt> <DerivedNormalizationProps.txt> <out.rs>
"""

import sys


def main():
    ud, dnp, dst = sys.argv[1], sys.argv[2], sys.argv[3]
    excluded = set()
    for line in open(dnp, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line:
            continue
        fields = [f.strip() for f in line.split(";")]
        if len(fields) < 2 or fields[1] != "Full_Composition_Exclusion":
            continue
        cps = fields[0]
        a, b = (cps.split("..") + [None])[:2]
        a = int(a, 16)
        b = int(b, 16) if b else a
        excluded.update(range(a, b + 1))
    decomp = []
    for line in open(ud, encoding="utf-8"):
        f = line.rstrip("\n").split(";")
        if len(f) < 6 or not f[5] or f[5].startswith("<"):
            continue
        cp = int(f[0], 16)
        parts = [int(x, 16) for x in f[5].split()]
        assert 1 <= len(parts) <= 2, line
        decomp.append((cp, parts[0], parts[1] if len(parts) == 2 else 0))
    decomp.sort()
    compose = sorted((a, b, cp) for cp, a, b in decomp if b != 0 and cp not in excluded)
    dm = {cp: (a, b) for cp, a, b in decomp}
    cm = {(a, b): cp for a, b, cp in compose}
    assert cm[(0x65, 0x301)] == 0xE9 and cm[(0x41, 0x30A)] == 0xC5
    assert (0x915, 0x93C) not in cm and dm[0x958] == (0x915, 0x93C)
    assert dm[0x212B] == (0xC5, 0)
    out = [
        "//! Canonical composition and decomposition, generated by",
        "//! `scripts/gen-compose.py` from `[[source: unicode-data]]` and",
        "//! `[[source: unicode-dnp]]`. Do not edit; regenerate.",
        "",
        "/// `(first, second, composed)`, sorted by `(first, second)`: the primary",
        "/// composites. Hangul syllables are not listed; they compose by",
        "/// arithmetic.",
        "pub const COMPOSE: &[(u32, u32, u32)] = &[",
    ]
    out += [f"    (0x{a:04X}, 0x{b:04X}, 0x{c:04X})," for a, b, c in compose]
    out += ["];", "", "/// `(codepoint, first, second)`, sorted by codepoint; `second` is 0 for a",
            "/// singleton. One level deep.",
            "pub const DECOMPOSE: &[(u32, u32, u32)] = &["]
    out += [f"    (0x{cp:04X}, 0x{a:04X}, 0x{b:04X})," for cp, a, b in decomp]
    out += ["];", ""]
    open(dst, "w").write("\n".join(out))
    print(f"{dst}: {len(compose)} composites, {len(decomp)} decompositions, {len(excluded)} exclusions")


if __name__ == "__main__":
    main()
