"""HarfBuzz's varied outlines, as baud-font's gvar oracle.

Writes baud-font/tests/var/outlines.txt: for each committed variable test
font, a sample of its glyphs -- every glyph whose id is a multiple of 37,
which reaches simple and composite glyphs alike -- and every glyph of
tests/var/gvar-cases.ttf (tools/baud-oracle cases gvar), drawn by HarfBuzz at
the default instance and at the settings named below, as the commands its
draw functions emit, in font units (the font's scale is its units per em).
The default rows are the control: they say HarfBuzz's emission rule is
baud's before a varied row is compared at all.

    nix shell --impure --expr 'with import (builtins.getFlake "nixpkgs") {}; \
      python3.withPackages (p: [ p.uharfbuzz ])' -c python3 scripts/gvar-oracle.py
"""
import os
import uharfbuzz as hb

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
# (font, settings, glyph step). 700 is the weight the embedded Bold is baked
# at; the others sit between masters and at the axis ends. The cases font's
# grid crosses each of its regions' edges on both axes.
CASES = [
    {"wght": w, "wdth": d}
    for w in (100, 250, 400, 460, 520, 580, 640, 700, 900)
    for d in (50, 75, 100, 150, 200)
    if (w, d) != (400, 100)
]
FONTS = [
    ("fonts/JetBrainsMono-Variable.ttf", [{"wght": w} for w in (100, 350, 700, 800)], 37),
    ("fonts/JetBrainsMono-Italic-Variable.ttf", [{"wght": w} for w in (100, 700, 800)], 37),
    ("fonts/FiraCode-VF.ttf", [{"wght": w} for w in (300, 550, 700)], 37),
    ("var/gvar-cases.ttf", CASES, 1),
]


def draw(font, gid):
    out = []
    funcs = hb.DrawFuncs()
    funcs.set_move_to_func(lambda x, y, c: c.append(f"M {x:.4f} {y:.4f}"))
    funcs.set_line_to_func(lambda x, y, c: c.append(f"L {x:.4f} {y:.4f}"))
    funcs.set_quadratic_to_func(
        lambda cx, cy, x, y, c: c.append(f"Q {cx:.4f} {cy:.4f} {x:.4f} {y:.4f}")
    )
    funcs.set_cubic_to_func(lambda *a: a[-1].append("C"))
    funcs.set_close_path_func(lambda c: c.append("Z"))
    font.draw_glyph(gid, funcs, out)
    return out


lines = [
    "# font  axis=value,... (or - for the default)  glyph  commands  (HarfBuzz "
    + hb.version_string() + ", uharfbuzz " + hb.__version__ + ")",
    "# generated by scripts/gvar-oracle.py; do not edit",
]
for name, settings, step in FONTS:
    blob = hb.Blob.from_file_path(os.path.join(ROOT, "baud-font/tests", name))
    face = hb.Face(blob)
    for setting in [None] + settings:
        font = hb.Font(face)
        font.scale = (face.upem, face.upem)
        tag = "-"
        if setting is not None:
            font.set_variations(setting)
            tag = ",".join(f"{k}={v}" for k, v in setting.items())
        for gid in range(0, face.glyph_count, step):
            cmds = draw(font, gid)
            lines.append(f"{name} {tag} {gid} " + " ".join(cmds))
with open(os.path.join(ROOT, "baud-font/tests/var/outlines.txt"), "w") as f:
    f.write("\n".join(lines) + "\n")
print(len(lines) - 2, "glyph rows")
