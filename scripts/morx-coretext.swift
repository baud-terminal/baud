// Records CoreText's shaping of every morx fixture, for the oracle test
// every_morx_fixture_shapes_as_coretext_does: each line of morx.txt with
// CoreText's glyphs, clusters, offsets and advances appended in hb-shape notation.
// swift scripts/morx-coretext.swift < baud-font/tests/shape/morx.txt > baud-font/tests/shape/morx-coretext.txt
import CoreText
import Foundation

let v = ProcessInfo.processInfo.operatingSystemVersion
let os = v.patchVersion == 0 ? "\(v.majorVersion).\(v.minorVersion)" : "\(v.majorVersion).\(v.minorVersion).\(v.patchVersion)"
print("# generated by scripts/morx-coretext.swift with CoreText on macOS \(os)")
print("# columns: path, face index, fnv64 of the file, hb-shape features, codepoints, hb-shape, CoreText")
while let row = readLine() {
    if row.hasPrefix("#") || row.isEmpty { continue }
    let f = row.components(separatedBy: "\t")
    let path = f[0], index = Int(f[1])!, feats = f[3], cps = f[4]
    let descs = CTFontManagerCreateFontDescriptorsFromURL(URL(fileURLWithPath: path) as CFURL) as! [CTFontDescriptor]
    let probe = CTFontCreateWithFontDescriptor(descs[index], 12, nil)
    let upem = CGFloat(CTFontGetUnitsPerEm(probe))
    let font = CTFontCreateWithFontDescriptor(descs[index], upem, nil)
    let ps = CTFontCopyPostScriptName(font) as String
    let scalars = cps.split(separator: " ").map { Unicode.Scalar(UInt32($0, radix: 16)!)! }
    var s = ""
    var u16ToCp: [Int] = []
    for (i, sc) in scalars.enumerated() { s.unicodeScalars.append(sc); for _ in 0..<String(sc).utf16.count { u16ToCp.append(i) } }
    var attrs: [NSAttributedString.Key: Any] = [kCTFontAttributeName as NSAttributedString.Key: font,
                                                kCTKernAttributeName as NSAttributedString.Key: 0]
    if feats.contains("-liga") { attrs[kCTLigatureAttributeName as NSAttributedString.Key] = 0 }
    if feats.contains("--direction=ltr") {
        var dir = CTWritingDirection.leftToRight
        let set = [CTParagraphStyleSetting(spec: .baseWritingDirection, valueSize: MemoryLayout<CTWritingDirection>.size, value: &dir)]
        attrs[kCTParagraphStyleAttributeName as NSAttributedString.Key] = CTParagraphStyleCreate(set, 1)
    }
    let line = CTLineCreateWithAttributedString(NSAttributedString(string: s, attributes: attrs))
    var out: [String] = []
    var pen: CGFloat = 0
    for run in CTLineGetGlyphRuns(line) as! [CTRun] {
        let n = CTRunGetGlyphCount(run)
        var g = [CGGlyph](repeating: 0, count: n), p = [CGPoint](repeating: .zero, count: n)
        var a = [CGSize](repeating: .zero, count: n), ix = [CFIndex](repeating: 0, count: n)
        CTRunGetGlyphs(run, CFRange(location: 0, length: 0), &g)
        CTRunGetPositions(run, CFRange(location: 0, length: 0), &p)
        CTRunGetAdvances(run, CFRange(location: 0, length: 0), &a)
        CTRunGetStringIndices(run, CFRange(location: 0, length: 0), &ix)
        let rf = (CTRunGetAttributes(run) as NSDictionary)[kCTFontAttributeName] as! CTFont
        let rps = CTFontCopyPostScriptName(rf) as String
        for k in 0..<n {
            let id = rps == ps ? "\(g[k])" : "fb:\(rps):\(g[k])"
            let dx = Int((p[k].x - pen).rounded()), dy = Int(p[k].y.rounded())
            let off = (dx != 0 || dy != 0) ? "@\(dx),\(dy)" : ""
            out.append("\(id)=\(u16ToCp[ix[k]])\(off)+\(Int(a[k].width.rounded()))")
            pen += a[k].width
        }
    }
    let ct = "[" + out.joined(separator: "|") + "]"
    print("\(row)\t\(ct)")
}
