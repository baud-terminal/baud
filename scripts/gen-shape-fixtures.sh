def compile_flags(chain, requested):
    flags = chain.DefaultFlags
    for fe in chain.MorphFeature:
        if (fe.FeatureType, fe.FeatureSetting) in requested:
            flags = (flags & fe.DisableFlags) | fe.EnableFlags
    return flags
off = []
for tag, on, off_sel in defaults:
    if on[0] not in exposed:
        continue
    if any(compile_flags(c, {on}) != c.DefaultFlags for c in chains):
        off.append((tag, off_sel))
