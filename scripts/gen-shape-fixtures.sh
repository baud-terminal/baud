    got = compile_flags(c, requested)
    if got != c.DefaultFlags:
        sys.exit("%s: HarfBuzz would reach flags %#x against the chain's %#x" % (path, got, c.DefaultFlags))
print(",".join("-" + t for t, _ in off) + ("," if off else "") + "-kern")
PY2
