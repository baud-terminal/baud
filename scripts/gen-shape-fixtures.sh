# `morx`: the AAT faces macOS ships, which have no GSUB, shaped by HarfBuzz's
# AAT path. baud runs each chain's default flags and nothing else. HarfBuzz
# reads `feat` and requests `liga`, `clig`, `calt` and `rlig` by default,
# and a request moves the flags off the defaults in either direction --
# Menlo's common ligatures are off by default and `+liga` turns them on,
# Helvetica's are on and `-liga` would turn them off. So the flags HarfBuzz
# would reach are simulated per face from the chain's own feature table
# (`Chain::compile_flags`), and only the requests that move them are
# cancelled; `kern` is always off, because `kerx` kerning is not shaping.
# Each line names the file, the face index, an FNV-1a digest of the file --
# so the test refuses to compare against a font the OS has since replaced
# -- and the features passed. Needs fontTools: run under
# `nix-shell -p harfbuzz python3Packages.fonttools`.
# The `--features` that leave HarfBuzz at a face's `morx` chain defaults:
# its default requests that would move a flag cancelled, `kern` off, and
# a failure if a request moves one either way.
morx_features() {
  python3 - "$1" "$2" <<'PY2'
import sys
from fontTools.ttLib import TTFont, TTCollection
path, index = sys.argv[1], int(sys.argv[2])
f = TTCollection(path, lazy=True).fonts[index] if path.endswith(".ttc") else TTFont(path, lazy=True)
exposed = {n.FeatureType for n in f["feat"].table.FeatureNames.FeatureName} if "feat" in f else set()
# HarfBuzz's default requests that map onto morx, as (tag, on selector, off selector).
defaults = [("liga", (1, 2), (1, 3)), ("clig", (1, 18), (1, 19)), ("calt", (36, 0), (36, 1)), ("rlig", (1, 0), (1, 1))]
chains = f["morx"].table.MorphChain
def compile_flags(chain, requested):
    flags = chain.DefaultFlags
    for fe in chain.MorphFeature:
        if (fe.FeatureType, fe.FeatureSetting) in requested:
            flags = (flags & fe.DisableFlags) | fe.EnableFlags
    return flags
off = []
for tag, on, off_sel in defaults:
    if on[0] not in exposed:
        continue
    if any(compile_flags(c, {on}) != c.DefaultFlags for c in chains):
        off.append((tag, off_sel))
requested = {on for tag, on, _ in defaults if on[0] in exposed and tag not in {t for t, _ in off}} | {sel for _, sel in off}
for c in chains:
    got = compile_flags(c, requested)
    if got != c.DefaultFlags:
        sys.exit("%s: HarfBuzz would reach flags %#x against the chain's %#x" % (path, got, c.DefaultFlags))
print(",".join("-" + t for t, _ in off) + ("," if off else "") + "-kern")
PY2
}

