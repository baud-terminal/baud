"""HarfBuzz's CFF2 outlines, as baud-font's CFF2 oracle.

Writes baud-font/tests/var/cff2-outlines.txt: every glyph whose id is a
multiple of 7 in Source Code VF (tests/fonts/SourceCodeVF-Upright.otf), and
every glyph of tests/var/cff2-cases.otf (tools/baud-oracle cases cff2), drawn
by HarfBuzz at the default instance and at the settings named below, as the
commands its draw functions emit, in font units (the font's scale is its
units per em). Every coordinate is printed as Python's repr of the float
HarfBuzz handed over, which is the C float exactly, so the comparison can
be exact; a cubic carries all six of its coordinates. The default rows are
the control: they say HarfBuzz's emission rule is baud's before a varied
row is compared at all.

    nix shell --impure --expr 'with import (builtins.getFlake "nixpkgs") {}; \
      python3.withPackages (p: [ p.uharfbuzz ])' -c python3 scripts/cff2-oracle.py
"""
import os
import uharfbuzz as hb

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
# Source Code VF's one axis is wght 200-900, default 200; 637 sits between
# masters. The cases font's grid crosses each of its regions' peaks and
# edges on both axes.
CASES = [
    {"wght": w, "wdth": d}
    for w in (100, 250, 400, 525, 650, 900)
    for d in (50, 100, 137, 200)
    if (w, d) != (400, 100)
]
FONTS = [
    ("fonts/SourceCodeVF-Upright.otf", [{"wght": w} for w in (250, 400, 637, 900)], 7),
    ("var/cff2-cases.otf", CASES, 1),
]


def draw(font, gid):
    out = []
    funcs = hb.DrawFuncs()
    funcs.set_move_to_func(lambda x, y, c: c.append(f"M {x!r} {y!r}"))
    funcs.set_line_to_func(lambda x, y, c: c.append(f"L {x!r} {y!r}"))
    funcs.set_quadratic_to_func(lambda cx, cy, x, y, c: c.append(f"Q {cx!r} {cy!r} {x!r} {y!r}"))
    funcs.set_cubic_to_func(
        lambda c1x, c1y, c2x, c2y, x, y, c: c.append(
            f"C {c1x!r} {c1y!r} {c2x!r} {c2y!r} {x!r} {y!r}"
        )
    )
    funcs.set_close_path_func(lambda c: c.append("Z"))
    font.draw_glyph(gid, funcs, out)
    return out


lines = [
    "# font  axis=value,... (or - for the default)  glyph  commands  (HarfBuzz "
    + hb.version_string() + ", uharfbuzz " + hb.__version__ + ")",
    "# generated by scripts/cff2-oracle.py; do not edit",
]
for name, settings, step in FONTS:
    blob = hb.Blob.from_file_path(os.path.join(ROOT, "baud-font/tests", name))
    face = hb.Face(blob)
    for setting in [None] + settings:
        font = hb.Font(face)
        font.scale = (face.upem, face.upem)
        label = "-"
        if setting:
            font.set_variations(setting)
            label = ",".join(f"{k}={v}" for k, v in setting.items())
        for gid in range(0, face.glyph_count, step):
            lines.append(f"{name} {label} {gid} " + " ".join(draw(font, gid)))

out = os.path.join(ROOT, "baud-font/tests/var/cff2-outlines.txt")
with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
print(out, len(lines) - 2)
