#!/usr/bin/env python3
"""Format the cluster transition table dumped by baud-domain's test.

    cargo test --release -p baud-domain --test cluster_states -- --ignored
    python3 scripts/gen-cluster-table.py
    python3 scripts/gen-cluster-table.py --check   # cluster_data.rs is current

Byte strings, not array literals: rustfmt rewraps `[0, 1, ...]`, so the file the
generator writes would not be the file that gets committed.
"""
import struct, sys, pathlib

raw = pathlib.Path("baud-domain/cluster.bin").read_bytes()
(n,) = struct.unpack_from("<I", raw, 0)
table = raw[4 : 4 + n * 256]
ready = raw[4 + n * 256 : 4 + n * 256 + n]
at = 4 + n * 257
legacy = raw[at : at + n * 32]
marks = raw[at + n * 32 : at + n * 64]
assert len(raw) == 4 + n * 257 + n * 64, f"cluster.bin is {len(raw)} bytes for {n} states"
assert list(ready).count(1) == 1, f"ready states: {[i for i, r in enumerate(ready) if r]}"
rid = ready.index(1)

def bytestr(v, per=24):
    return "\\\n    ".join(
        "".join(f"\\x{b:02x}" for b in v[i : i + per]) for i in range(0, len(v), per)
    )

src = f'''//! Generated by `baud-domain/tests/cluster_states.rs::emit_cluster_table` and
//! `scripts/gen-cluster-table.py`. Do not edit.
//!
//! **UAX #29 as a transition table.** `decide` walks the GB rules in order and
//! `advance` writes back four fields; both are branchy, and on emoji-heavy text
//! the branches are exactly the unpredictable ones. The machine's whole state
//! is `prev`, `ri`, `pict` and `incb` -- 270 combinations nominally and
//! **{n} reachable** -- and its input is the byte the flat property table
//! already returns, four bits of class and four of lookback.
//!
//! So the transition fits one byte: bit 7 is the break decision, bits 0..7 the
//! next state. {n} x 256 = {len(table)} bytes, and the whole machine becomes a
//! `u8` plus one indexed load.
//!
//! `the_cluster_table_agrees_with_the_rules` replays every reachable state
//! against every input through the rule implementation.

/// Bit 7 is "break here", bits 0..7 are the next state.
pub static CLUSTER_NEXT: &[u8; {len(table)}] = b"\\
    {bytestr(table)}";

/// The one state in which a run of ordinary characters is provably a no-op --
/// `prev` is `Other` with no lookback live. `ordinary_run_ready` is now a
/// compare against this rather than four field tests.
pub const CLUSTER_READY: u8 = {rid};

/// States reachable from the initial one.
#[allow(dead_code)]
pub const CLUSTER_STATES: usize = {n};

/// **Where a join parts under legacy clusters**: one bit per (state, input),
/// bit `i & 7` of byte `i >> 3` for `i = state * 256 + input`, set where the
/// extended rules join and the legacy ones -- without GB9a, GB9b and GB9c --
/// break. Read only where the machine joined; {len(legacy)} bytes.
pub static CLUSTER_PARTS_LEGACY: &[u8; {len(legacy)}] = b"\\
    {bytestr(legacy)}";

/// The same, with spacing marks joined: without GB9b and GB9c.
pub static CLUSTER_PARTS_MARKS_JOINED: &[u8; {len(marks)}] = b"\\
    {bytestr(marks)}";
'''
out = pathlib.Path("baud-domain/src/cluster_data.rs")
if "--check" in sys.argv:
    if out.read_text() != src:
        print("STALE: cluster_data.rs is not what cluster.bin formats to")
        sys.exit(1)
    print("OK")
else:
    out.write_text(src)
    print(f"  cluster_data.rs: {n} states, {len(table)} bytes, ready state = {rid}")
