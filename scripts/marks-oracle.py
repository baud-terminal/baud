"""HarfBuzz's mark positions at a variation, as baud-font's GPOS oracle.

Writes baud-font/tests/var/marks.txt: each committed variable test font
shaped by HarfBuzz with the mark features on and everything else a grid
cannot use off -- the feature set tests/shape/gpos.txt uses -- at the
default instance and at the settings named below. Each row is one text:
its codepoints, then per glyph the id, cluster, x and y offset and x
advance, in font units (the font's scale is its units per em). The texts
are every letter of the fonts' Latin coverage under one mark from a set
of combining marks above and below, and some stacks of two, which is
where mark-to-mark anchors move. The default rows are the control that
the two agree before a varied row is compared.

    nix shell --impure --expr 'with import (builtins.getFlake "nixpkgs") {}; \\
      python3.withPackages (p: [ p.uharfbuzz ])' -c python3 scripts/marks-oracle.py
"""
import os
import uharfbuzz as hb

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
TESTS = os.path.join(ROOT, "baud-font/tests")
FEATURES = {"mark": True, "mkmk": True, "liga": False, "clig": False, "calt": False,
            "kern": False, "locl": False, "rclt": False, "dlig": False, "hlig": False}
MARKS = [0x0300, 0x0301, 0x0302, 0x0303, 0x0304, 0x0306, 0x0307, 0x0308,
         0x030A, 0x030B, 0x030C, 0x0323, 0x0326, 0x0327, 0x0328, 0x0331]
BASES = [c for c in range(0x41, 0x5B)] + [c for c in range(0x61, 0x7B)] + [0x131, 0x237]
STACKS = [(b, m1, m2) for b in (0x61, 0x6F, 0x75, 0x41, 0x4F, 0x69)
          for m1, m2 in ((0x0308, 0x0301), (0x0302, 0x0303), (0x0323, 0x0302),
                         (0x0304, 0x0300), (0x0327, 0x0306))]
TEXTS = [(b, m) for b in BASES for m in MARKS] + STACKS
# var/ink-cases.ttf (scripts/ink-cases-font.py) has no GPOS, so its marks
# are placed by the fallback against varied glyph boxes; it maps two bases
# and six marks, so it takes its own texts.
INK_MARKS = [0x0300, 0x0301, 0x0304, 0x030A, 0x0323, 0x0327]
INK_TEXTS = [(b, m) for b in (0x61, 0x6F) for m in INK_MARKS] + [
    (b, m1, m2) for b in (0x61, 0x6F)
    for m1, m2 in ((0x0304, 0x0301), (0x0301, 0x030A), (0x0323, 0x0301), (0x0327, 0x0300))]
FONTS = [
    ("fonts/JetBrainsMono-Variable.ttf", [{"wght": w} for w in (100, 350, 700, 800)], TEXTS),
    ("fonts/JetBrainsMono-Italic-Variable.ttf", [{"wght": w} for w in (100, 700, 800)], TEXTS),
    ("fonts/FiraCode-VF.ttf", [{"wght": w} for w in (300, 550, 700)], TEXTS),
    ("var/ink-cases.ttf", [{"wght": w} for w in (100, 250, 650, 900)], INK_TEXTS),
]

rows = 0
with open(os.path.join(TESTS, "var/marks.txt"), "w") as out:
    out.write(f"# font  axis=value,... (or - for the default)  codepoints  "
              f"glyph,cluster,dx,dy,ax;...  (HarfBuzz {hb.version_string()}, "
              f"uharfbuzz {hb.__version__})\n")
    out.write("# generated by scripts/marks-oracle.py; do not edit\n")
    for name, settings, texts in FONTS:
        face = hb.Face(hb.Blob.from_file_path(os.path.join(TESTS, name)))
        for s in [{}] + settings:
            font = hb.Font(face)
            if s:
                font.set_variations(s)
            label = ",".join(f"{k}={v}" for k, v in s.items()) or "-"
            for text in texts:
                buf = hb.Buffer()
                buf.add_codepoints(list(text))
                buf.guess_segment_properties()
                hb.shape(font, buf, FEATURES)
                glyphs = ";".join(
                    f"{i.codepoint},{i.cluster},{p.x_offset},{p.y_offset},{p.x_advance}"
                    for i, p in zip(buf.glyph_infos, buf.glyph_positions))
                cps = ",".join(f"{c:04X}" for c in text)
                out.write(f"{name} {label} {cps} {glyphs}\n")
                rows += 1
print(rows, "rows")
