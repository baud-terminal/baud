//! The Rust a table compiles to, and the bytes beside it.

use crate::Source;
use std::fmt::Write as _;
use std::path::Path;

/// One generated module, `<name>.rs`, and the `.bin` files its byte
/// statics include, held in memory: the build script's `main` alone writes
/// them to `OUT_DIR` ([`Emit::write`]), so a build module stays a function
/// of its inputs. The Rust carries only `//` and `///` comments, since an
/// inner `//!` is refused in an `include!`d file (E0753).
#[derive(Debug)]
pub struct Emit {
    name: String,
    rs: String,
    bins: Vec<(String, Vec<u8>)>,
}

impl Emit {
    /// A module named `name`, built by `by` (`baud-domain/build.rs
    /// (build/bidi.rs)`) from `sources`, which its header names with their
    /// keys.
    pub fn new(name: &str, by: &str, sources: &[&Source]) -> Emit {
        let from: Vec<String> = sources
            .iter()
            .map(|s| format!("{} [{}]", s.path(), s.key()))
            .collect();
        let mut rs = format!("// Generated by {by} from\n");
        for (i, f) in from.iter().enumerate() {
            let end = if i + 1 == from.len() { "." } else { "," };
            let _ = writeln!(rs, "// {f}{end}");
        }
        Emit {
            name: name.to_string(),
            rs,
            bins: Vec::new(),
        }
    }

    fn doc(&mut self, doc: &[&str]) {
        self.rs.push('\n');
        for l in doc {
            if l.is_empty() {
                self.rs.push_str("///\n");
            } else {
                let _ = writeln!(self.rs, "/// {l}");
            }
        }
    }

    /// `pub static <ident>: &[u8; N]`, its bytes in `<ident>.bin`
    /// lower-cased and `include_bytes!`d, so the compiler reads them as
    /// bytes rather than parsing them as literals.
    pub fn bytes(&mut self, ident: &str, doc: &[&str], data: &[u8]) {
        let file = format!("{}.bin", ident.to_ascii_lowercase());
        self.doc(doc);
        let _ = writeln!(
            self.rs,
            "pub static {ident}: &[u8; {}] =\n    include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{file}\"));",
            data.len()
        );
        self.bins.push((file, data.to_vec()));
    }

    /// `pub static <ident>: [<ty>; N] = [...]`, `per_line` values a line,
    /// each written by `fmt`.
    pub fn array<T>(
        &mut self,
        ident: &str,
        ty: &str,
        doc: &[&str],
        data: &[T],
        per_line: usize,
        fmt: impl Fn(&T) -> String,
    ) {
        self.doc(doc);
        let _ = writeln!(self.rs, "pub static {ident}: [{ty}; {}] = [", data.len());
        for chunk in data.chunks(per_line.max(1)) {
            let line: Vec<String> = chunk.iter().map(&fmt).collect();
            let _ = writeln!(self.rs, "    {},", line.join(", "));
        }
        self.rs.push_str("];\n");
    }

    /// A compile-time pin of the enum at `ty` (a path from the including
    /// crate's root) to the order its discriminants are stored in: each of
    /// `variants` must be the discriminant of its position, and the match
    /// must be exhaustive, so a variant the data has no value for is E0004
    /// and a value with no variant is E0425.
    pub fn enum_order(&mut self, ty: &str, variants: &[&str]) {
        let list = variants.join(", ");
        let arms = variants.join(" | ");
        let _ = write!(
            self.rs,
            "\n// The table stores `{ty}` as its discriminants: each is its\n\
             // position in the data's order.\n\
             const _: () = {{\n    \
             use {ty}::*;\n    \
             let order = [{list}];\n    \
             let mut i = 0;\n    \
             while i < order.len() {{\n        \
             assert!(order[i] as usize == i, \"{ty} is not declared in the table's order\");\n        \
             i += 1;\n    \
             }}\n    \
             match order[0] {{\n        \
             {arms} => {{}}\n    \
             }}\n\
             }};\n"
        );
    }

    /// Rust written as it is.
    pub fn code(&mut self, text: &str) {
        self.rs.push('\n');
        self.rs.push_str(text);
        if !text.ends_with('\n') {
            self.rs.push('\n');
        }
    }

    /// The generated Rust.
    pub fn rust(&self) -> &str {
        &self.rs
    }

    /// Every file, by its name in `OUT_DIR`: `<name>.rs`, then the `.bin`s.
    pub fn files(&self) -> Vec<(String, &[u8])> {
        let mut out = vec![(format!("{}.rs", self.name), self.rs.as_bytes())];
        out.extend(self.bins.iter().map(|(f, b)| (f.clone(), b.as_slice())));
        out
    }

    /// Writes [`Emit::files`] into `dir`. Only a build script's `main`
    /// calls this.
    pub fn write(&self, dir: &Path) -> std::io::Result<()> {
        for (f, b) in self.files() {
            std::fs::write(dir.join(f), b)?;
        }
        Ok(())
    }
}
