//! tmux, fish, wcwidth, lipgloss and ratatui; one in neovim and vim; three under
//! macOS libc), so they keep one cell until that is decided.
//!
//! `BASES` is generated from the pinned file and
//! `the_vs16_bases_are_the_pinned_files_emoji_style_sequences` holds it to it.

