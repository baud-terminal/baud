use std::path::{Path, PathBuf};
use std::process::ExitCode;

/// The HarfBuzz every committed oracle file was made with.
pub const HARFBUZZ: &str = "12.3.0";
/// The FreeType the drawing oracles were made with.
pub const FREETYPE: &str = "2.14.3";

/// One oracle: the file it writes, relative to the root, and the lines.
pub struct Oracle {
    /// The bin's name.
    pub name: &'static str,
    /// The file it writes, relative to the repository's root.
    pub file: &'static str,
    /// Every line of the file, headers first, without newlines.
    pub lines: fn(&Path) -> Vec<String>,
}

/// The repository this crate sits in.
pub fn repo() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// The generator line every file's header carries.
pub fn generated_by(name: &str) -> String {
    format!("# generated by tools/baud-oracle's {name} bin; do not edit")
}

/// The binding named in a header's engine list, beside the engines.
pub const BINDING: &str = "tools/baud-oracle";

/// Refuse to write a line unless the linked engines are the pinned ones:
/// an oracle on another engine version is a different oracle.
pub fn pinned(free_type: Option<&ft::Library>) {
    let hb = hb::version();
    assert_eq!(
        hb, HARFBUZZ,
        "linked HarfBuzz {hb}, not the pinned {HARFBUZZ}"
    );
    if let Some(l) = free_type {
        let v = l.version();
        assert_eq!(
            v, FREETYPE,
            "linked FreeType {v}, not the pinned {FREETYPE}"
        );
    }
}

/// The engine versions a header names: every `HarfBuzz x` and `FreeType y`.
pub fn engines(header: &str) -> Vec<String> {
    let words: Vec<&str> = header
        .split(|c: char| c.is_whitespace() || c == '(' || c == ')' || c == ',')
        .filter(|w| !w.is_empty())
        .collect();
    words
        .windows(2)
        .filter(|w| w[0] == "HarfBuzz" || w[0] == "FreeType")
        .map(|w| format!("{} {}", w[0], w[1]))
        .collect()
}

/// Refuse to rasterise unless the linked FreeType is the pinned one.
pub fn pinned_freetype(l: &ft::Library) {
    let v = l.version();
    assert_eq!(
        v, FREETYPE,
        "linked FreeType {v}, not the pinned {FREETYPE}"
    );
}

/// What `--check` compares: the data lines exactly, and the engines the
/// header names. `Err` says what differs first.
pub fn compare(have: &[String], committed: &str) -> Result<(), String> {
    let data = |it: &mut dyn Iterator<Item = String>| -> Vec<String> {
        it.filter(|l| !l.starts_with('#')).collect()
    };
    let head = |it: &mut dyn Iterator<Item = String>| -> Vec<String> {
        it.filter(|l| l.starts_with('#'))
            .flat_map(|l| engines(&l))
            .collect()
    };
    let theirs = || committed.lines().map(str::to_string);
    let (a, b) = (data(&mut have.iter().cloned()), data(&mut theirs()));
    if let Some(i) = (0..a.len().max(b.len())).find(|&i| a.get(i) != b.get(i)) {
        return Err(format!(
            "data line {} differs:\n  generated {:?}\n  committed {:?}",
            i + 1,
            a.get(i),
            b.get(i)
        ));
    }
    let (x, y) = (head(&mut have.iter().cloned()), head(&mut theirs()));
    if x != y {
        return Err(format!("the header's engines differ: {x:?} against {y:?}"));
    }
    if !committed.ends_with('\n') {
        return Err("the committed file does not end in a newline".to_string());
    }
    Ok(())
}

/// A bin's `main`: write the file, or `--check` it.
pub fn main(oracle: &Oracle) -> ExitCode {
    let mut args = std::env::args().skip(1);
    let (mut check, mut root) = (false, repo());
    while let Some(a) = args.next() {
        match a.as_str() {
            "--check" => check = true,
            "--root" => root = PathBuf::from(args.next().expect("--root DIR")),
            _ => {
                eprintln!("usage: {} [--check] [--root DIR]", oracle.name);
                return ExitCode::FAILURE;
            }
        }
    }
    let lines = (oracle.lines)(&root);
    let path = root.join(oracle.file);
    let rows = lines.iter().filter(|l| !l.starts_with('#')).count();
    if check {
        let committed = std::fs::read_to_string(&path).expect("the committed file");
        return match compare(&lines, &committed) {
            Ok(()) => {
                println!("{}: {rows} rows, as committed", oracle.file);
                ExitCode::SUCCESS
            }
            Err(e) => {
                eprintln!("{}: {e}", oracle.file);
                ExitCode::FAILURE
            }
        };
    }
    std::fs::write(&path, lines.join("\n") + "\n").expect("write the file");
    println!("{} {rows} rows", path.display());
    ExitCode::SUCCESS
}

/// A drawing as the contour oracles print it: each contour's points, or
/// `Q`/`C` where an engine emitted a curve.
#[derive(Clone, Copy, PartialEq)]
pub enum Item {
    /// An on-curve point, in font units.
    Point(f32, f32),
    /// A quadratic segment, or a contour FreeType holds an off-curve point
    /// in.
    Quad,
    /// A cubic segment.
    Cubic,
}

/// HarfBuzz's drawing of `glyph`, as the scripts' `contours_hb` collected
/// it: a contour per `move_to`, a point per `move_to` and `line_to`, `Q`
/// and `C` for curves, and the closing point dropped where it repeats the
/// first.
pub fn contours_hb(font: &hb::Font, glyph: u32) -> Vec<Vec<Item>> {
    struct Collect(Vec<Vec<Item>>);
    impl Collect {
        fn last(&mut self) -> &mut Vec<Item> {
            self.0.last_mut().expect("a segment after a move_to")
        }
    }
    impl hb::Pen for Collect {
        fn move_to(&mut self, x: f32, y: f32) {
            self.0.push(vec![Item::Point(x, y)]);
        }
        fn line_to(&mut self, x: f32, y: f32) {
            self.last().push(Item::Point(x, y));
        }
        fn quad_to(&mut self, _: f32, _: f32, _: f32, _: f32) {
            self.last().push(Item::Quad);
        }
        fn cubic_to(&mut self, _: f32, _: f32, _: f32, _: f32, _: f32, _: f32) {
            self.last().push(Item::Cubic);
        }
        fn close(&mut self) {}
    }
    let mut c = Collect(Vec::new());
    font.draw(glyph, &mut c);
    c.0.into_iter()
        .map(|mut c| {
            if c.len() > 1 && c.last() == c.first() {
                c.pop();
            }
            c
        })
        .collect()
}

/// FreeType's outline of `glyph`, loaded unscaled and unhinted, as the
/// scripts' `contours_ft` read it: a contour's points, or `Q` alone for a
/// contour holding an off-curve point. `Err` carries what freetype-py's
/// exception printed.
pub fn contours_ft(face: &mut ft::Face, glyph: u32) -> Result<Vec<Vec<Item>>, String> {
    let outline = face.load_unscaled(glyph).map_err(ft::exception)?;
    Ok(outline
        .iter()
        .map(|c| {
            if c.tags.iter().any(|t| t & ft::CURVE_TAG_ON == 0) {
                vec![Item::Quad]
            } else {
                // `float(x)` of a font-unit integer is exact in f32 too.
                c.points
                    .iter()
                    .map(|p| Item::Point(p.x as f32, p.y as f32))
                    .collect()
            }
        })
        .collect())
}

/// The scripts' `fmt`: `-` for no contours, else contours by `|` and points
/// by `;`, each coordinate `{:.4f}`.
pub fn fmt(contours: &[Vec<Item>]) -> String {
    if contours.is_empty() {
        return "-".to_string();
    }
    let item = |i: &Item| match *i {
        Item::Point(x, y) => format!(
            "{},{}",
            pyfmt::fixed(f64::from(x), 4),
            pyfmt::fixed(f64::from(y), 4)
        ),
        Item::Quad => "Q".to_string(),
        Item::Cubic => "C".to_string(),
    };
    contours
        .iter()
        .map(|c| c.iter().map(item).collect::<Vec<_>>().join(";"))
        .collect::<Vec<_>>()
        .join("|")
}

/// A FreeType row: the drawing, or `ERROR` and the exception with its
/// spaces made underscores.
pub fn ft_row(face: &mut ft::Face, glyph: u32) -> String {
    match contours_ft(face, glyph) {
        Ok(c) => fmt(&c),
        Err(e) => format!("ERROR {}", e.replace(' ', "_")),
    }
}

/// A glyph's name as uharfbuzz's `get_glyph_name` returned it, and as an
/// f-string printed `None`.
pub fn name(font: &hb::Font, glyph: u32) -> String {
    font.glyph_name(glyph).unwrap_or_else(|| "None".to_string())
}

/// `",".join(f"{k}={v}" for k, v in s.items()) or "-"`, for integer values.
pub fn label(axes: &[(&str, i32)]) -> String {
    if axes.is_empty() {
        return "-".to_string();
    }
    axes.iter()
        .map(|(k, v)| format!("{k}={v}"))
        .collect::<Vec<_>>()
        .join(",")
}

/// Integer axis settings as the `f64` uharfbuzz's dict held.
pub fn as_float<'a>(axes: &[(&'a str, i32)]) -> Vec<(&'a str, f64)> {
    axes.iter().map(|&(k, v)| (k, f64::from(v))).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_header_names_its_engines() {
        let h = "# glyph  name  (HarfBuzz 12.3.0, uharfbuzz 0.53.2, FreeType 2.14.3)";
        assert_eq!(engines(h), ["HarfBuzz 12.3.0", "FreeType 2.14.3"]);
    }

    /// **The positive controls of `--check`**: a changed data line, a
    /// changed engine, and a dropped row each fail it.
    #[test]
    fn check_fires_on_a_line_an_engine_and_a_row() {
        let have: Vec<String> = ["# x (HarfBuzz 12.3.0)", "a 1", "b 2"]
            .map(str::to_string)
            .to_vec();
        assert!(compare(&have, "# y (HarfBuzz 12.3.0, z)\na 1\nb 2\n").is_ok());
        assert!(compare(&have, "# x (HarfBuzz 12.3.0)\na 1\nb 3\n").is_err());
        assert!(compare(&have, "# x (HarfBuzz 13.2.1)\na 1\nb 2\n").is_err());
        assert!(compare(&have, "# x (HarfBuzz 12.3.0)\na 1\n").is_err());
    }

    #[test]
    fn a_label_is_the_dict_s_items() {
        assert_eq!(label(&[]), "-");
        assert_eq!(label(&[("wght", 100), ("wdth", 50)]), "wght=100,wdth=50");
    }

    #[test]
    fn fmt_is_the_scripts() {
        assert_eq!(fmt(&[]), "-");
        let c = vec![
            vec![Item::Point(0.0, -0.0), Item::Quad],
            vec![Item::Point(1.5, 2.0)],
        ];
        assert_eq!(fmt(&c), "0.0000,-0.0000;Q|1.5000,2.0000");
    }
}
