//! **The reference-engine oracles**: HarfBuzz 12.3.0 and FreeType 2.14.3
//! run on the committed test fonts, their answers written to
//! `crates/baud-font/tests/var/*.txt`, and libxkbcommon 1.13.2 on baud-xkb's
//! keymaps and Compose tables, its answers written to
//! `crates/baud-xkb/tests/fixtures/`; the tests read both with no tool on their
//! path.
//!
//! One bin per oracle, each the port of the Python script that wrote its
//! file before it, call for call and format for format:
//!
//! | bin | writes | asks |
//! |---|---|---|
//! | `advance` | `advances.txt` | `hb_font_get_glyph_h_advance` at a variation |
//! | `bearing` | `bearings.txt` | both engines' drawings of the bearing cases, and each glyph's pp1 |
//! | `cff2` | `cff2-outlines.txt` | `hb_font_draw_glyph` on CFF2, every coordinate as Python's `repr` |
//! | `component` | `components.txt` | both engines' drawings of the component cases |
//! | `gvar` | `outlines.txt` | `hb_font_draw_glyph` on glyf and gvar |
//! | `marks` | `marks.txt` | `hb_shape` with the mark features |
//! | `var` | `normalize.txt` | `hb_font_get_var_coords_normalized` |
//! | `vertical` | `vertical.txt` | both engines' drawings of the vertical cases |
//!
//! And one bin, `baud-oracle`, for the oracles a test or a script runs
//! and for the cases fonts:
//!
//! | subcommand | writes | asks |
//! |---|---|---|
//! | `xkb` | `crates/baud-xkb/tests/fixtures/oracle-*.txt` and `compose/oracle-*.txt` | libxkbcommon's keymap state and Compose tables ([`xkb`]) |
//! | `raster` | stdout, for `crates/baud-font/tests/raster.rs` | FreeType's unhinted smooth bitmaps ([`raster`]) |
//! | `shape-helpers` | stdout, for `tools/scripts/gen-shape-fixtures.sh` | nothing: digests, code points and `morx` defaults beside hb-shape ([`shape`]) |
//! | `cases` | the cases fonts under `crates/baud-font/tests/var/` | nothing: each font built from its recipe on write-fonts ([`cases`]) |
//!
//! Run from the repository's root, in the shell that pins the engines:
//!
//! ```text
//! nix-shell tools/shell.nix --run \
//!   'cargo run --release --manifest-path tools/Cargo.toml --bin advance'
//! ```
//!
//! `--check` writes nothing and fails unless every data line equals the
//! committed file's and the header names the same engine versions.
//! `--root DIR` reads the fonts from, and writes under, another tree.
//!
//! **Outside the workspace**, with its own `Cargo.lock`, so `cargo test
//! --workspace` and the push hook never build or link a C engine.

