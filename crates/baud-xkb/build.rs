//! **The keysym tables, generated from the pinned `xkbcommon-keysyms.h`.**
//! Every `#define XKB_KEY_<name> 0x<value>` becomes a name-to-value entry,
//! and the `/* U+XXXX ... */` comment the header carries beside a keysym
//! with a Unicode equivalent becomes a value-to-codepoint entry. Nothing
//! is transcribed; the header is `[[source: xkbcommon-keysyms]]`, hashed
//! in the manifest, and read through `crates/baud-xkb/xkbcommon-keysyms.h`, a
//! link to it that the published crate carries as the file.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

fn main() {
    let manifest = env::var("CARGO_MANIFEST_DIR").unwrap();
    let path = Path::new(&manifest).join("xkbcommon-keysyms.h");
    println!("cargo:rerun-if-changed={}", path.display());
    println!("cargo:rerun-if-changed=build.rs");
    let text = fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let mut names: Vec<(String, u32)> = Vec::new();
    let mut unicode: Vec<(u32, u32)> = Vec::new();
    for line in text.lines() {
        let Some(rest) = line.strip_prefix("#define XKB_KEY_") else {
            continue;
        };
        let mut it = rest.split_whitespace();
        let (Some(name), Some(value)) = (it.next(), it.next()) else {
            continue;
        };
        let Some(hex) = value.strip_prefix("0x") else {
            continue;
        };
        let Ok(v) = u32::from_str_radix(hex, 16) else {
            continue;
        };
        names.push((name.to_string(), v));
        if let Some(c) = line.find("/* U+") {
            let tail = &line[c + 5..];
            let end = tail
                .find(|ch: char| !ch.is_ascii_hexdigit())
                .unwrap_or(tail.len());
            if let Ok(cp) = u32::from_str_radix(&tail[..end], 16) {
                // The first name for a value wins, as the header lists the
                // canonical spelling first.
                if unicode.last().map(|(k, _)| *k) != Some(v) {
                    unicode.push((v, cp));
                }
            }
        }
    }
    assert!(
        names.len() > 2000,
        "the header should declare thousands of keysyms"
    );
    // Sorted by name for a binary search; the first spelling of a value is
    // the canonical one and later aliases keep their own entries.
    names.sort_by(|a, b| a.0.cmp(&b.0));
    names.dedup_by(|a, b| a.0 == b.0);
    unicode.sort_by_key(|(k, _)| *k);
    unicode.dedup_by_key(|(k, _)| *k);
    let mut o = String::new();
    writeln!(
        o,
        "// Generated by build.rs from the pinned xkbcommon-keysyms.h. Do not edit."
    )
    .unwrap();
    writeln!(o, "/// Keysym names and values, sorted by name.").unwrap();
    writeln!(o, "pub static NAMES: &[(&str, u32)] = &[").unwrap();
    for (n, v) in &names {
        writeln!(o, "    (\"{n}\", {v:#x}),").unwrap();
    }
    writeln!(o, "];").unwrap();
    writeln!(
        o,
        "/// Keysym values with a Unicode equivalent the header names, sorted by value."
    )
    .unwrap();
    writeln!(o, "pub static UNICODE: &[(u32, u32)] = &[").unwrap();
    for (v, cp) in &unicode {
        writeln!(o, "    ({v:#x}, {cp:#x}),").unwrap();
    }
    writeln!(o, "];").unwrap();
    let out = Path::new(&env::var("OUT_DIR").unwrap()).join("keysyms.rs");
    fs::write(out, o).unwrap();
}
