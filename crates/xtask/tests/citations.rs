//! `cargo xtask citations`: the list it writes is the list it checks, each
//! of its checks fires, a merge adds a fragment's rows once with each
//! item's path, and the repository's own list is current.

mod common;

use std::fs;
use std::path::{Path, PathBuf};

use common::base;
use xtask::citations::{self, Mode};
use xtask::third_party::Outcome;

const M: &str = "docs/research/sources/MANIFEST.toml";

fn cite(key: &str) -> String {
    format!("[[source: {key}]]")
}

#[test]
fn the_base_tree_lists_what_it_cites_and_commits() {
    let t = base();
    let (o, out) = t.citations();
    assert_eq!(o, Outcome::Passed, "{out}");
    assert_eq!(
        out,
        "  ok   51 sources listed in docs/citations.md, 0 code items\n"
    );
    let md = t.read(citations::OUT);
    assert!(md.starts_with("# Citations\n\n<!-- Generated by "), "{md}");
    assert!(md.contains(citations::GENERATOR), "{md}");
    assert!(
        md.contains("<a id=\"doc-a\"></a>\n### doc-a\n"),
        "the committed entry is anchored by its key:\n{md}"
    );
    assert!(
        md.contains("- **Copy:** [docs/research/sources/a.txt](research/sources/a.txt)\n"),
        "{md}"
    );
    assert!(
        md.contains("- **Copy:** not committed; cited by URL and sha256\n"),
        "{md}"
    );
    assert!(md.contains("- **Cited in:** `docs/notes.md`\n"), "{md}");
    assert!(
        !md.contains("gated-x"),
        "an uncited gated entry is listed:\n{md}"
    );
    assert!(
        !md.contains("[[source: "),
        "the list spells a citation the source gate would read:\n{md}"
    );
}

fn fails_with(t: &common::Tree, line: &str) {
    let (o, out) = t.citations();
    assert_eq!(o, Outcome::Failed, "the check passed:\n{out}");
    assert!(
        out.lines().any(|l| l.starts_with(line)),
        "no line {line:?} in:\n{out}"
    );
}

#[test]
fn a_new_citation_leaves_the_list_stale() {
    let t = base();
    t.append("docs/more.md", &format!("Also {}.\n", cite("doc-a")));
    fails_with(
        &t,
        "  FAIL docs/citations.md is stale: run cargo xtask citations",
    );
}

#[test]
fn a_changed_title_leaves_the_list_stale() {
    let t = base();
    t.edit(M, "title  = \"Doc A\"", "title  = \"Doc A, again\"");
    fails_with(
        &t,
        "  FAIL docs/citations.md is stale: run cargo xtask citations",
    );
}

#[test]
fn a_missing_list() {
    let t = base();
    t.remove(citations::OUT);
    fails_with(
        &t,
        "  FAIL docs/citations.md is missing: run cargo xtask citations",
    );
}

#[test]
fn every_code_row_check_fires() {
    for (rows, line) in [
        (
            "docs/notes.md::claim\tno-such-key\twhat it supports\n",
            "  FAIL docs/data/citations-code.tsv: docs/notes.md::claim names no-such-key, which the manifest does not carry",
        ),
        (
            "docs/notes.md::claim\tgated-x\twhat it supports\n",
            "  FAIL docs/data/citations-code.tsv: docs/notes.md::claim names gated-x, recorded as gated",
        ),
        (
            "docs/gone.rs::f\tdoc-a\twhat it supports\n",
            "  FAIL docs/data/citations-code.tsv: docs/gone.rs::f names docs/gone.rs, which is not in the tree",
        ),
        (
            "docs/notes.md::claim\tdoc-a\tone\ndocs/notes.md::claim\tdoc-a\ttwo\n",
            "  FAIL docs/data/citations-code.tsv: docs/notes.md::claim under doc-a twice",
        ),
        (
            "docs/notes.md::claim\tdoc-a\n",
            "  FAIL docs/data/citations-code.tsv:5: 2 columns",
        ),
    ] {
        let t = base();
        t.append(citations::CODE, rows);
        fails_with(&t, line);
    }
}

#[test]
fn a_merge_adds_a_fragments_rows_once_and_lists_them() {
    let t = base();
    let frag = t.path("fragment.tsv");
    fs::write(
        &frag,
        "docs/notes.md::claim\tdoc-a\t3-5\tthe claim's wording\n",
    )
    .expect("a fragment");
    let frag = frag.to_str().expect("a path").to_string();
    for added in ["  ok   1 rows added", "  ok   0 rows added"] {
        let mut out = Vec::new();
        let o = citations::merge(&t.0, &[frag.as_str()], &mut out).expect("a merge");
        let out = String::from_utf8(out).expect("UTF-8");
        assert_eq!(o, Outcome::Passed, "{out}");
        assert!(out.starts_with(added), "{out}");
    }
    let code = t.read(citations::CODE);
    assert!(
        code.ends_with("\ndocs/notes.md::claim\tdoc-a\tthe claim's wording\n"),
        "{code}"
    );
    let md = t.read(citations::OUT);
    assert!(
        md.contains("- **Supports:**\n  - `docs/notes.md::claim`: the claim's wording\n"),
        "{md}"
    );
    let (o, out) = t.citations();
    assert_eq!(o, Outcome::Passed, "{out}");
    assert!(out.contains("1 code items"), "{out}");
}

/// `--merge` of `rows` as a fragment of the staged tree.
fn merged(t: &common::Tree, rows: &str) -> (Outcome, String, String) {
    let frag = t.path("fragment.tsv");
    fs::write(&frag, rows).expect("a fragment");
    t.stage();
    let frag = frag.to_str().expect("a path").to_string();
    let mut out = Vec::new();
    let o = citations::merge(&t.0, &[frag.as_str()], &mut out).expect("a merge");
    (o, String::from_utf8(out).expect("UTF-8"), frag)
}

#[test]
fn a_merge_gives_each_item_the_path_of_the_file_that_defines_it() {
    let t = base();
    t.put(
        "src/a.rs",
        "pub fn claim() {}\nmod host {\n    pub(crate) fn twice() {}\n}\n",
    );
    t.put("src/b.rs", "fn twice() {}\n");
    t.put("docs/research/sources/up.rs", "pub fn claim() {}\n");
    let (o, out, _) = merged(
        &t,
        "claim\tdoc-a\tone\nhost::twice\tdoc-a\t3-4\ttwo\nsrc/b.rs::twice\tdoc-a\tthree\n",
    );
    assert_eq!(o, Outcome::Passed, "{out}");
    assert!(out.starts_with("  ok   3 rows added"), "{out}");
    let code = t.read(citations::CODE);
    for row in [
        "\nsrc/a.rs::claim\tdoc-a\tone\n",
        "\nsrc/a.rs::host::twice\tdoc-a\ttwo\n",
        "\nsrc/b.rs::twice\tdoc-a\tthree\n",
    ] {
        assert!(code.contains(row), "no row {row:?} in:\n{code}");
    }
}

#[test]
fn a_merge_writes_nothing_when_an_item_is_not_in_one_file() {
    let t = base();
    t.put("src/a.rs", "fn twice() {}\n");
    t.put("src/b.rs", "fn twice() {}\n");
    t.put("src/c.rs", "fn only() {}\n");
    let before = t.read(citations::CODE);
    let (o, out, frag) = merged(
        &t,
        "twice\tdoc-a\tone\nnowhere\tdoc-a\ttwo\nOuter::only\tdoc-a\tthree\n",
    );
    assert_eq!(o, Outcome::Failed, "{out}");
    for line in [
        format!(
            "  FAIL {frag}: twice: src/a.rs, src/b.rs define twice; write the row as path::twice"
        ),
        format!(
            "  FAIL {frag}: nowhere: no tracked .rs file defines nowhere; write the row as path::nowhere"
        ),
        format!(
            "  FAIL {frag}: Outer::only: no tracked .rs file defines only and names Outer; write the row as path::Outer::only"
        ),
    ] {
        assert!(
            out.lines().any(|l| l == line),
            "no line {line:?} in:\n{out}"
        );
    }
    assert_eq!(t.read(citations::CODE), before);
}

#[test]
fn a_word_is_never_part_of_a_longer_name() {
    assert!(citations::holds_word("mod host {", "host"));
    assert!(citations::holds_word("host", "host"));
    assert!(!citations::holds_word("hosts host_tests ghost", "host"));
    assert!(!citations::holds_word("anything", ""));
}

#[test]
fn text_is_shown_and_never_marks_anything_up() {
    assert_eq!(
        citations::escaped("a `b` <c> [d](e) *f* g_h & i\\"),
        "a &#96;b&#96; &lt;c&gt; &#91;d&#93;(e) \\*f\\* g\\_h &amp; i\\\\"
    );
}

#[test]
fn the_read_date_is_the_one_the_comments_give() {
    let m = "# Fetched\n# 2026-01-02, for the next entry.\n[sources.a]\nkey = \"a\"\n\
             # Not in the repository. Version 2025-12-31.\n\n[sources.b]\nkey = \"b\"\n\
             # The page as read 2026-03-04.\n\n[sources.c]\nkey = \"c\"\n";
    let c = citations::comments(m);
    assert_eq!(citations::read_date(&c["a"]).as_deref(), Some("2026-01-02"));
    assert_eq!(citations::read_date(&c["b"]).as_deref(), Some("2026-03-04"));
    assert_eq!(
        c.get("c")
            .map(String::as_str)
            .and_then(citations::read_date),
        None
    );
}

fn repository() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .expect("the repository")
}

/// The repository's docs/citations.md is what the generator writes from the
/// tree, and every check behind it passes.
#[test]
fn the_repositorys_list_is_current() {
    let mut out = Vec::new();
    let o = citations::run(&repository(), Mode::Check, &mut out).expect("a run");
    assert_eq!(o, Outcome::Passed, "{}", String::from_utf8_lossy(&out));
}
