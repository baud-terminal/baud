//! Every check of `cargo xtask third-party --check` fires, and the file it
//! writes is the file it checks. The repository's own sidecar leaves no
//! file's licence open.

mod common;

use common::{base, run, third_party_cases};
use xtask::credits;
use xtask::publish::UNSETTLED;
use xtask::third_party::{self, Outcome, Side};

/// The repository's sidecar settles every file it lists: no group and no
/// [[tree]] row is under a status that leaves the file's licence a choice
/// still open.
#[test]
fn every_file_in_the_repository_has_its_licence_settled() {
    let root = credits::root_of(env!("CARGO_MANIFEST_DIR"));
    let table = third_party::load(&root, third_party::SIDECAR).expect("the sidecar reads");
    let side = Side::of(&table).expect("the sidecar parses");
    assert!(
        !side.upstream.is_empty() && !side.tree.is_empty(),
        "the sidecar lists no row"
    );
    let mut open: Vec<String> = side
        .upstream
        .iter()
        .filter(|g| UNSETTLED.contains(&g.status))
        .map(|g| format!("upstream.{} ({})", g.id, g.status))
        .collect();
    open.extend(
        side.tree
            .iter()
            .filter(|t| UNSETTLED.contains(&t.status))
            .map(|t| format!("{:?} ({})", t.paths, t.status)),
    );
    assert!(open.is_empty(), "rows still open: {open:#?}");
}

#[test]
fn the_base_tree_passes() {
    let (o, out) = base().third_party();
    assert_eq!(o, Outcome::Passed, "{out}");
    assert_eq!(
        out,
        "  ok   1 sources and 10 other entries indexed, 1 licence texts, 55 fonts\n"
    );
}

/// A notice that is not in a source's comment is no file's notice: a
/// string holding one, and a document quoting one, need no row.
#[test]
fn a_notice_outside_a_source_comment_needs_no_row() {
    let t = base();
    t.put(
        "tools/quotes.rs",
        "fn f(s: &str) -> bool {\n    s.contains(\"Copyright (c) 2031 Someone\")\n}\n",
    );
    t.put("docs/quotes.md", "Copyright (c) 2031 Someone\n");
    let (o, out) = t.third_party();
    assert_eq!(o, Outcome::Passed, "{out}");
}

/// The repository's own sources and directories of other works' files
/// meet the row checks: what `rowed` finds wrong in the tracked tree,
/// with the fonts and the notices at or above their floors.
#[test]
fn the_repository_rows_its_notices_and_other_works_files() {
    let root = credits::root_of(env!("CARGO_MANIFEST_DIR"));
    let table = third_party::load(&root, third_party::SIDECAR).expect("the sidecar reads");
    let side = Side::of(&table).expect("the sidecar parses");
    let files = xtask::no_python::tracked(&root).expect("git ls-files");
    let (errs, _) = third_party::rowed(&root, &side, &files);
    assert!(errs.is_empty(), "{errs:#?}");
}

#[test]
fn every_third_party_check_fires() {
    for case in third_party_cases() {
        let (o, out) = run(&case);
        assert_eq!(o, Outcome::Failed, "{}: the gate passed:\n{out}", case.name);
        assert!(
            out.lines().any(|l| l.starts_with(case.expect)),
            "{}: no line {:?} in:\n{out}",
            case.name,
            case.expect
        );
    }
}

#[test]
fn writing_refuses_a_tree_that_fails_and_leaves_the_file() {
    let t = base();
    let before = t.read("THIRD_PARTY.md");
    t.put("LICENSES/extra.txt", "x\n");
    let mut out = Vec::new();
    let o = third_party::run(&t.0, third_party::Mode::Write, &mut out).expect("a run");
    assert_eq!(o, Outcome::Failed);
    assert_eq!(t.read("THIRD_PARTY.md"), before);
}

#[test]
fn the_written_file_names_its_generator() {
    let t = base();
    let md = t.read("THIRD_PARTY.md");
    assert!(
        md.starts_with("# Third-party files in baud\n\n<!-- Generated by "),
        "{md}"
    );
    assert!(md.contains(third_party::GENERATOR), "{md}");
}
