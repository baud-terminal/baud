//! The cell shader's copy of the stress mark's skip trie,
//! `OUT_DIR/stress_skips.metal`: `baud_render::STRESS_SKIP_INDEX` and
//! `STRESS_SKIP_BLOCKS` as `uchar` arrays of the same bytes, which
//! `baud-render`'s build compiles from the pinned UCD files and hands
//! over in its `OUT_DIR`. `src/shaders.metal` includes the file by name,
//! so the Metal compiler reads it with `-I OUT_DIR`, and the build also
//! writes `OUT_DIR/shaders.metal`, the shaders with the file spliced in
//! where the include stands: the text the runtime compiles when the
//! library will not load, and the text the library's digest is of.
//!
//! A pure function of its inputs: `main` reads them and writes what these
//! return.

/// The include, by the name the shaders give it.
pub const INCLUDE: &str = "stress_skips.metal";

/// The line of `src/shaders.metal` the include is spliced over.
pub const LINE: &str = "#include \"stress_skips.metal\"";

/// The trie's stage 1: one block number for each 256 codepoints.
const INDEX_LEN: usize = 0x1100;

/// A block of stage 2: 256 bits.
const BLOCK: usize = 32;

/// The include's text, refused when the bytes are not a trie's.
pub fn metal(index: &[u8], blocks: &[u8]) -> Result<String, String> {
    if index.len() != INDEX_LEN {
        return Err(format!(
            "STRESS_SKIP_INDEX has {} entries, {INDEX_LEN} expected",
            index.len()
        ));
    }
    if blocks.is_empty() || !blocks.len().is_multiple_of(BLOCK) {
        return Err(format!(
            "STRESS_SKIP_BLOCKS has {} bytes, not whole blocks of {BLOCK}",
            blocks.len()
        ));
    }
    let n = blocks.len() / BLOCK;
    if let Some(b) = index.iter().find(|&&b| usize::from(b) >= n) {
        return Err(format!("STRESS_SKIP_INDEX names block {b}, of {n} blocks"));
    }
    let mut out = format!(
        "// Generated by crates/baud-present-macos/build.rs (build/stress.rs) from\n\
         // `baud_render::STRESS_SKIP_INDEX` and `STRESS_SKIP_BLOCKS`, the same\n\
         // bytes: {n} blocks. Pinned by `the_stress_mark_table_matches_the_shader`.\n"
    );
    for (name, data) in [("STRESS_SKIP_INDEX", index), ("STRESS_SKIP_BLOCKS", blocks)] {
        out.push_str(&format!("constant uchar {name}[{}] = {{\n", data.len()));
        for chunk in data.chunks(16) {
            let line: Vec<String> = chunk.iter().map(|v| format!("0x{v:02x}")).collect();
            out.push_str(&format!("    {},\n", line.join(", ")));
        }
        out.push_str("};\n");
    }
    Ok(out)
}

/// `shader` with `include` in place of its one [`LINE`]; refused, at the
/// line and column of each, unless there is exactly one.
pub fn splice(path: &str, shader: &str, include: &str) -> Result<String, String> {
    let at: Vec<usize> = shader
        .lines()
        .enumerate()
        .filter(|(_, l)| l.trim_end() == LINE)
        .map(|(i, _)| i + 1)
        .collect();
    match at.as_slice() {
        [_] => {}
        [] => return Err(format!("{path}: no `{LINE}` line to splice the table over")),
        [first, rest @ ..] => {
            let more: Vec<String> = rest.iter().map(|l| format!("{path}:{l}:1")).collect();
            return Err(format!(
                "{path}:{first}:1: `{LINE}` is given {} times, once expected; again at {}",
                at.len(),
                more.join(", ")
            ));
        }
    }
    let mut out = String::with_capacity(shader.len() + include.len());
    for line in shader.split_inclusive('\n') {
        if line.trim_end() == LINE {
            out.push_str(include);
        } else {
            out.push_str(line);
        }
    }
    Ok(out)
}
