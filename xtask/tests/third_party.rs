//! Every check of `cargo xtask third-party --check` fires, and the file it
//! writes is the file it checks.

mod common;

use std::fs;

use common::{base, run, third_party_cases};
use xtask::third_party::{self, Outcome, STATUS};

#[test]
fn the_base_tree_passes() {
    let (o, out) = base().third_party();
    assert_eq!(o, Outcome::Passed, "{out}");
    assert_eq!(
        out,
        "  ok   1 sources and 2 other entries indexed, 1 licence texts, 30 LICENSE paths\n"
    );
}

#[test]
fn every_third_party_check_fires() {
    for case in third_party_cases() {
        let (o, out) = run(&case);
        assert_eq!(o, Outcome::Failed, "{}: the gate passed:\n{out}", case.name);
        assert!(
            out.lines().any(|l| l.starts_with(case.expect)),
            "{}: no line {:?} in:\n{out}",
            case.name,
            case.expect
        );
    }
}

#[test]
fn writing_refuses_a_tree_that_fails_and_leaves_the_file() {
    let t = base();
    let before = t.read("THIRD_PARTY.md");
    t.put("LICENSES/extra.txt", "x\n");
    let mut out = Vec::new();
    let o = third_party::run(&t.0, third_party::Mode::Write, &mut out).expect("a run");
    assert_eq!(o, Outcome::Failed);
    assert_eq!(t.read("THIRD_PARTY.md"), before);
}

#[test]
fn the_written_file_names_its_generator() {
    let t = base();
    let md = t.read("THIRD_PARTY.md");
    assert!(
        md.starts_with("# Third-party files in baud\n\n<!-- Generated by "),
        "{md}"
    );
    assert!(md.contains(third_party::GENERATOR), "{md}");
}

/// `scripts/check-publish.py` writes each crate's NOTICE with the status
/// meanings and licence URIs THIRD_PARTY.md uses, from its own copy of
/// both until it is ported; this holds the copy to the tables here.
#[test]
fn check_publish_carries_the_same_meanings_and_uris() {
    let py = fs::read_to_string(concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../scripts/check-publish.py"
    ))
    .expect("scripts/check-publish.py");
    for (status, meaning) in STATUS {
        let row = format!("\"{status}\": \"{meaning}\",");
        assert!(py.contains(&row), "check-publish.py lacks {row}");
    }
    for spdx in [
        "CC-BY-4.0",
        "CC-BY-SA-4.0",
        "CC-BY-ND-4.0",
        "CC-BY-NC-SA-3.0",
        "CC0-1.0",
        "LicenseRef-W3C-Document",
        "LicenseRef-IETF-RFC",
        "LicenseRef-Ecma-Copyright",
    ] {
        let uri = third_party::licence_uri(spdx).expect("a URI");
        let row = format!("\"{spdx}\": \"{uri}\",");
        assert!(py.contains(&row), "check-publish.py lacks {row}");
    }
}
